// Bundles the runtime into one script for the sandbox Worker and writes it as a TypeScript string
// (src/generated/worker.ts), so the app embeds exactly the code the tests run.
//   node scripts/build-worker.mjs           write the file
//   node scripts/build-worker.mjs --check   fail if it is out of date
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src/generated/worker.ts');

export async function workerSource() {
  const out = await build({
    entryPoints: [join(root, 'src/worker-entry.ts')],
    bundle: true,
    format: 'iife',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    write: false,
  });
  const js = out.outputFiles[0].text.trim();
  return `// Generated by scripts/build-worker.mjs — do not edit. Run \`pnpm --filter @funnest/script build:worker\`.\n/** The Funnest Script v2 runtime, bundled for the sandbox Worker (sets globalThis.__funnestScript). */\nexport const SCRIPT_WORKER_SOURCE = ${JSON.stringify(js)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await workerSource();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8').replace(/\r\n?/g, '\n');
    } catch {}
    if (current !== text) {
      console.error('src/generated/worker.ts is out of date: run `pnpm --filter @funnest/script build:worker`.');
      process.exit(1);
    }
    console.log('worker source up to date');
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
    console.log(`wrote ${target} (${(text.length / 1024).toFixed(1)} KB)`);
  }
}
