// Builds the machine-readable docs from src/spec.ts and examples/: llms.txt (for AI assistants),
// funnest-script.d.ts (types) and reference.json, into docs/ (published with the package; the site serves them at funnest.xyz/scripts/…).
//   node scripts/build-docs.mjs           write the files
//   node scripts/build-docs.mjs --check   fail if any is out of date
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'docs');
const { GROUPS, MISTAKES, RULES, TYPES } = await import(new URL('../src/spec.ts', import.meta.url).href);

// One line ending everywhere: a Windows checkout (CRLF) must build the same files as Linux.
const lf = (text) => text.replace(/\r\n?/g, '\n');

const examples = readdirSync(join(root, 'examples'))
  .filter((f) => f.endsWith('.js'))
  .sort()
  .map((file) => ({ file, code: lf(readFileSync(join(root, 'examples', file), 'utf8')).trim() }));
// Larger examples written for Funnest: in the app's templates and the tests, not in llms.txt.
const showcase = readdirSync(join(root, 'showcase'))
  .filter((f) => f.endsWith('.js'))
  .sort()
  .map((file) => ({ file, code: lf(readFileSync(join(root, 'showcase', file), 'utf8')).trim() }));

const TEMPLATE = `//@version=2
indicator({ name: 'My indicator', overlay: true })
const len = input.int('Length', 20, { min: 2 })
const ma = ta.ema(close, len)
plot('EMA', ma, { color: color.orange })`;

function llms() {
  const out = [];
  out.push('# Funnest Script v2', '');
  out.push(
    '> The indicator and strategy language of Funnest (https://funnest.xyz/trade). A script is plain JavaScript that runs once over all bars of a chart, with the names below in scope. Reply with code only: one script, no explanations unless asked.',
    '',
  );
  out.push('## Rules', '');
  RULES.forEach((r, i) => out.push(`${i + 1}. ${r.en}`));
  out.push('', 'Labels, names and inputs may be in Korean (the platform is Korean); keep code identifiers in English.', '');
  out.push('## Template', '', '```js', TEMPLATE, '```', '');
  out.push('## Types', '', '```ts', TYPES, '```', '');
  out.push('## Names in scope', '');
  for (const g of GROUPS) {
    out.push(`### ${g.en}`, '');
    for (const item of g.items) out.push(`- \`${item.name}\` — \`${item.ts}\` — ${item.en}${item.example ? ` Example: \`${item.example}\`` : ''}`);
    out.push('');
  }
  out.push('## Common mistakes', '');
  for (const m of MISTAKES) out.push(`- ${m.en}: \`${m.wrong}\` → \`${m.right}\``);
  out.push('', '## Errors', '', 'A failed run reports a code (SERIES_ARITHMETIC, CONDITION_IN_IF, MISSING_DECLARATION, BAD_ARG, FORBIDDEN, LIMIT, SYNTAX, RUNTIME), the line, and a hint with the fix. Apply the hint literally.', '');
  out.push('## Examples', '');
  for (const e of examples) out.push(`### ${e.file}`, '', '```js', e.code, '```', '');
  return out.join('\n');
}

function dts() {
  const out = ['// Funnest Script v2 — declarations for editors and AI tools. Generated from src/spec.ts.', '', TYPES, ''];
  const nested = new Map();
  for (const g of GROUPS)
    for (const item of g.items) {
      const dot = item.name.indexOf('.');
      if (dot > 0 && item.name !== 'bar.count') {
        const ns = item.name.slice(0, dot);
        if (!nested.has(ns)) nested.set(ns, []);
        nested.get(ns).push(`  /** ${item.en} */\n  ${item.ts};`);
      } else out.push(`/** ${item.en} */`, `declare ${item.ts};`, '');
    }
  for (const [ns, members] of nested) out.push(`declare const ${ns}: {`, ...members, '};', '');
  return out.join('\n');
}

function reference() {
  return `${JSON.stringify({ version: 2, rules: RULES, mistakes: MISTAKES, types: TYPES, groups: GROUPS, examples }, null, 2)}\n`;
}

const llmsText = llms();
const dtsText = dts();
const files = { 'llms.txt': llmsText, 'funnest-script.d.ts': dtsText, 'reference.json': reference() };
// The same text inside the app (the editor's "AI로 만들기" copies it).
const appCopy = join(root, 'src/generated/llms.ts');
const appText = `// Generated by scripts/build-docs.mjs — do not edit.
/** llms.txt: the whole language for an AI assistant (also at https://funnest.xyz/scripts/llms.txt). */
export const LLMS_TEXT = ${JSON.stringify(llmsText)};
/** funnest-script.d.ts: the declarations scripts are type-checked against. */
export const DTS_TEXT = ${JSON.stringify(dtsText)};
/** The example scripts (examples/*.js). */
export const EXAMPLES: { file: string; code: string }[] = ${JSON.stringify(examples)};
/** Larger examples (showcase/*.js), written for Funnest: for the app's templates. */
export const SHOWCASE: { file: string; code: string }[] = ${JSON.stringify(showcase)};
`;
if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([name, text]) => {
    try {
      return lf(readFileSync(join(outDir, name), 'utf8')) !== text;
    } catch {
      return true;
    }
  });
  try {
    if (lf(readFileSync(appCopy, 'utf8')) !== appText) stale.push(['src/generated/llms.ts']);
  } catch {
    stale.push(['src/generated/llms.ts']);
  }
  if (stale.length) {
    console.error(`out of date: ${stale.map(([n]) => n).join(', ')} — run \`pnpm --filter @funnest/script build:docs\`.`);
    process.exit(1);
  }
  console.log('docs up to date');
} else {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(appCopy, appText);
  for (const [name, text] of Object.entries(files)) {
    writeFileSync(join(outDir, name), text);
    console.log(`wrote ${name} (${(text.length / 1024).toFixed(1)} KB)`);
  }
}
